import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { JSDOM, VirtualConsole } from 'jsdom';
for (const mode of ['source','rich']) test('bundled renderer opens '+mode+' notes in the instant editor', async () => {
  const errors = []; const vc = new VirtualConsole(); vc.on('jsdomError',e => errors.push(e.message));
  const dom = new JSDOM(fs.readFileSync('index.html','utf8'),{runScripts:'outside-only',pretendToBeVisual:true,url:'http://localhost',virtualConsole:vc});
  const w=dom.window;
  w.Range.prototype.getClientRects=()=>[];
  w.Range.prototype.getBoundingClientRect=()=>({left:0,right:0,top:0,bottom:0,width:0,height:0});
  w.notes={load:async()=>({id:'test',mode,color:'sage',content:'# 测试\n\n1. 第一\n2. 第二',pinned:false}),save:()=>({ok:true})};
  w.eval(fs.readFileSync('dist/renderer.js','utf8'));
  await new Promise(resolve=>setTimeout(resolve,100));
  assert.equal(w.document.getElementById('status').textContent,'Saved locally');
  assert.ok(w.document.querySelector('.tiptap[contenteditable=true]'));
  assert.equal(w.document.querySelector('.tiptap h1').textContent,'测试');
  assert.deepEqual(errors,[]);
  w.close();
});
test('popover opens and animates closed before hiding', async () => {
  const dom = new JSDOM(fs.readFileSync('index.html','utf8'),{runScripts:'outside-only',pretendToBeVisual:true,url:'http://localhost'});
  const w=dom.window, menu=w.document.getElementById('menu'), more=w.document.getElementById('more');
  w.notes={load:async()=>({id:'test',mode:'source',tone:18,content:'',pinned:false}),save:()=>({ok:true})};
  w.eval(fs.readFileSync('dist/renderer.js','utf8'));
  await new Promise(resolve=>setTimeout(resolve,50));
  assert.equal(w.document.querySelector('[data-tone="18"]').getAttribute('aria-pressed'),'true');
  assert.equal(w.document.getElementById('toneValue').textContent,'18%');
  more.click(); await new Promise(resolve=>setTimeout(resolve,0));
  assert.equal(menu.hidden,false);
  more.click(); await new Promise(resolve=>setTimeout(resolve,0));
  assert.ok(menu.classList.contains('leaving'));
  await new Promise(resolve=>setTimeout(resolve,300));
  assert.equal(menu.hidden,true); assert.ok(!menu.classList.contains('leaving'));
  w.close();
});
test('notes with tables open read-only so the file is not rewritten', async () => {
  let saves=0;
  const dom = new JSDOM(fs.readFileSync('index.html','utf8'),{runScripts:'outside-only',pretendToBeVisual:true,url:'http://localhost'});
  const w=dom.window;
  w.notes={load:async()=>({id:'test',mode:'source',color:'sage',content:'| a | b |\n|---|---|\n| 1 | 2 |',pinned:false}),save:()=>{saves++;return{ok:true};}};
  w.eval(fs.readFileSync('dist/renderer.js','utf8'));
  await new Promise(resolve=>setTimeout(resolve,100));
  assert.ok(w.document.querySelector('.tiptap[contenteditable=false]'));
  assert.ok(w.document.querySelector('[data-format=bold]').disabled);
  w.dispatchEvent(new w.Event('blur'));
  assert.equal(saves,0);
  w.close();
});
test('dark tones switch the whole window to light ink', async () => {
  const metas=[];
  const dom = new JSDOM(fs.readFileSync('index.html','utf8'),{runScripts:'outside-only',pretendToBeVisual:true,url:'http://localhost'});
  const w=dom.window;
  w.Range.prototype.getClientRects=()=>[];
  w.Range.prototype.getBoundingClientRect=()=>({left:0,right:0,top:0,bottom:0,width:0,height:0});
  w.notes={load:async()=>({id:'test',mode:'rich',content:'# Hi',pinned:false}),save:()=>({ok:true}),meta:async p=>{metas.push(p);return p;}};
  w.eval(fs.readFileSync('dist/renderer.js','utf8'));
  await new Promise(resolve=>setTimeout(resolve,50));
  const body=w.document.body;
  assert.equal(body.style.getPropertyValue('--paper'),'hsl(0 0% 100%)');
  w.document.querySelector('[data-tone="100"]').click();
  assert.equal(body.style.getPropertyValue('--ink'),'#f2f2f2');
  assert.equal(body.style.colorScheme,'dark');
  await new Promise(resolve=>setTimeout(resolve,20));
  assert.equal(JSON.stringify(metas),'[{"tone":100}]');
  w.close();
});
